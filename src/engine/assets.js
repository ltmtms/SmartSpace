export const ASSET_BY_ID = Object.fromEntries(ASSETS.map((a) => [a.id, a]));
export const ASSET_CATEGORIES = [...new Set(ASSETS.map((a) => a.cat))];

export function buildAsset(id) {
  const def = ASSET_BY_ID[id];
  const group = new THREE.Group();
  if (!def) return group;
  const mats = new Map();
  for (const [g, color, scale, pos, rot] of def.parts()) {
    if (!mats.has(color)) mats.set(color, new THREE.MeshStandardMaterial({ color, roughness: 0.75 }));
    const mesh = new THREE.Mesh(geo[g], mats.get(color));
    mesh.scale.set(...scale);
    mesh.position.set(...pos);
    if (rot) mesh.rotation.set(rot[0] * D, rot[1] * D, rot[2] * D);
    mesh.castShadow = mesh.receiveShadow = true;
    group.add(mesh);
  }
  return group;
}
