function quadruped(body, accent, { len = 0.9, h = 0.5, w = 0.4, leg = 0.4, head = 0.34, ears = 'point', tail = 'thin', snout = accent } = {}) {
  const lx = w / 2 - 0.07, lz = len / 2 - 0.1, y = leg + h / 2;
  const parts = [
    b(body, [w, h, len], [0, y, 0]),
    ...[[-lx, lz], [lx, lz], [-lx, -lz], [lx, -lz]].map(([x, z]) => b(accent, [0.12, leg, 0.12], [x, leg / 2, z])),
    b(body, [head, head, head], [0, y + h / 2, len / 2 + head / 4]),
    b(snout, [head * 0.5, head * 0.36, 0.14], [0, y + h / 2 - head * 0.16, len / 2 + head * 0.78]),
    s(EYE, 0.06, [-head * 0.25, y + h / 2 + head * 0.12, len / 2 + head * 0.75]),
    s(EYE, 0.06, [head * 0.25, y + h / 2 + head * 0.12, len / 2 + head * 0.75]),
  ];
  const ey = y + h / 2 + head / 2;
  if (ears === 'point') parts.push(py(accent, [0.12, 0.16, 0.12], [-head * 0.3, ey + 0.07, len / 2 + head / 4]), py(accent, [0.12, 0.16, 0.12], [head * 0.3, ey + 0.07, len / 2 + head / 4]));
  if (ears === 'flop') parts.push(b(accent, [0.08, 0.22, 0.14], [-head / 2 - 0.03, ey - 0.14, len / 2 + head / 4]), b(accent, [0.08, 0.22, 0.14], [head / 2 + 0.03, ey - 0.14, len / 2 + head / 4]));
  if (ears === 'horn') parts.push(k(WHITE, [0.07, 0.18, 0.07], [-head * 0.36, ey + 0.08, len / 2 + head / 4]), k(WHITE, [0.07, 0.18, 0.07], [head * 0.36, ey + 0.08, len / 2 + head / 4]));
  if (tail === 'thin') parts.push(b(accent, [0.07, 0.07, 0.36], [0, y + h * 0.3, -len / 2 - 0.15], [35, 0, 0]));
  if (tail === 'curl') parts.push(t(accent, 0.16, [0, y + h * 0.25, -len / 2 - 0.05], [0, 90, 0]));
  if (tail === 'bush') parts.push(s(accent, [0.16, 0.16, 0.42], [0, y + h * 0.3, -len / 2 - 0.2], [30, 0, 0]));
  return parts;
}

